#!/usr/bin/env python3

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
RUNTIME_PACKAGE = REPO_ROOT / "scripts" / "second_brain"
RUNTIME_MODULE_NAMES = tuple(
    sorted(
        path.name
        for path in RUNTIME_PACKAGE.glob("*.py")
        if not path.name.startswith("remove_")
    )
)
LEGACY_RUNTIME_TARGET_NAME = "state.py"
SERVICE = (
    REPO_ROOT
    / "dot_config"
    / "systemd"
    / "user"
    / "second-brain-checkpoint.service"
)
TIMER = (
    REPO_ROOT
    / "dot_config"
    / "systemd"
    / "user"
    / "second-brain-checkpoint.timer"
)
DEFERRED_SERVICE = (
    REPO_ROOT
    / "dot_config"
    / "systemd"
    / "user"
    / "second-brain-deferred.service"
)
DEFERRED_TIMER = (
    REPO_ROOT
    / "dot_config"
    / "systemd"
    / "user"
    / "second-brain-deferred.timer"
)

CHEZMOI_IGNORE = REPO_ROOT / ".chezmoiignore"


@unittest.skipUnless(shutil.which("chezmoi"), "chezmoi is required")
class SecondBrainTimerChezmoiTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tempdir = tempfile.TemporaryDirectory()
        self.addCleanup(self.tempdir.cleanup)
        self.root = Path(self.tempdir.name)

    def test_chezmoi_ignores_runtime_bytecode_mapping_collisions(self) -> None:
        source = self.root / "source"
        destination = self.root / "destination"
        package = source / "scripts" / "second_brain"
        bytecode = package / "__pycache__"
        bytecode.mkdir(parents=True)
        destination.mkdir()
        (source / ".chezmoiignore").write_bytes(CHEZMOI_IGNORE.read_bytes())
        (source / ".chezmoidata.toml").write_text(
            "gui = true\n",
            encoding="utf-8",
        )
        (package / "state_private.py").write_text(
            "# Runtime state module.\n",
            encoding="utf-8",
        )
        (package / "remove_state.py").write_text("", encoding="utf-8")
        for name in (
            "private_state.cpython-312.pyc",
            "remove_state.cpython-312.pyc",
            "state_private.cpython-312.pyc",
        ):
            (bytecode / name).write_bytes(b"generated bytecode fixture")

        completed = subprocess.run(
            [
                "chezmoi",
                "--source",
                str(source),
                "--destination",
                str(destination),
                "--persistent-state",
                str(self.root / "chezmoi-state.boltdb"),
                "managed",
            ],
            cwd=self.root,
            env={
                **os.environ,
                "HOME": str(destination),
                "XDG_CACHE_HOME": str(self.root / "cache"),
            },
            text=True,
            capture_output=True,
            check=False,
        )

        self.assertEqual(completed.returncode, 0, completed.stderr)
        self.assertNotIn("__pycache__", completed.stdout)

    def test_real_chezmoi_requires_absolute_applied_front_door(self) -> None:
        source = self.root / "source"
        destination = self.root / "destination"
        managed_front_door = source / "second-brain" / "README.md"
        applied_front_door = destination / "second-brain" / "README.md"
        managed_front_door.parent.mkdir(parents=True)
        managed_front_door.write_text("# Second Brain\n", encoding="utf-8")
        destination.mkdir()
        config = self.root / "chezmoi-config.toml"
        config.write_text("[data]\ngui = true\n", encoding="utf-8")
        common = [
            "chezmoi",
            "--config",
            str(config),
            "--source",
            str(source),
            "--destination",
            str(destination),
            "--persistent-state",
            str(self.root / "source-path-state.boltdb"),
            "source-path",
        ]
        env = {
            **os.environ,
            "HOME": str(destination),
            "XDG_CACHE_HOME": str(self.root / "source-path-cache"),
        }

        absolute = subprocess.run(
            [*common, str(applied_front_door)],
            cwd=self.root,
            env=env,
            text=True,
            capture_output=True,
            check=False,
        )
        relative = subprocess.run(
            [*common, "second-brain/README.md"],
            cwd=self.root,
            env=env,
            text=True,
            capture_output=True,
            check=False,
        )

        self.assertEqual(absolute.returncode, 0, absolute.stderr)
        self.assertEqual(Path(absolute.stdout.strip()), managed_front_door)
        self.assertNotEqual(relative.returncode, 0)

    def test_real_chezmoi_exact_apply_installs_clean_target_set(self) -> None:
        destination = self.root / "clean-destination"
        runtime_dir = destination / "scripts" / "second_brain"
        unit_dir = destination / ".config" / "systemd" / "user"
        runtime_dir.mkdir(parents=True)
        unit_dir.mkdir(parents=True)
        config = self.root / "chezmoi-config.toml"
        config.write_text("[data]\ngui = true\n", encoding="utf-8")
        launcher = destination / "scripts" / "second-brain"
        modules = [runtime_dir / name for name in RUNTIME_MODULE_NAMES]
        service = unit_dir / SERVICE.name
        timer = unit_dir / TIMER.name
        deferred_service = unit_dir / DEFERRED_SERVICE.name
        deferred_timer = unit_dir / DEFERRED_TIMER.name

        completed = subprocess.run(
            [
                "chezmoi",
                "--config",
                str(config),
                "--source",
                str(REPO_ROOT),
                "--destination",
                str(destination),
                "--persistent-state",
                str(self.root / "clean-install-state.boltdb"),
                "apply",
                str(launcher),
                *(str(path) for path in modules),
                str(runtime_dir / LEGACY_RUNTIME_TARGET_NAME),
                str(service),
                str(timer),
                str(deferred_service),
                str(deferred_timer),
            ],
            cwd=self.root,
            env={
                **os.environ,
                "HOME": str(destination),
                "XDG_CACHE_HOME": str(self.root / "clean-cache"),
            },
            text=True,
            capture_output=True,
            check=False,
        )

        self.assertEqual(completed.returncode, 0, completed.stderr)
        expected = {
            "scripts/second-brain",
            *(f"scripts/second_brain/{name}" for name in RUNTIME_MODULE_NAMES),
            f".config/systemd/user/{SERVICE.name}",
            f".config/systemd/user/{TIMER.name}",
            f".config/systemd/user/{DEFERRED_SERVICE.name}",
            f".config/systemd/user/{DEFERRED_TIMER.name}",
        }
        actual = {
            path.relative_to(destination).as_posix()
            for path in destination.rglob("*")
            if path.is_file() or path.is_symlink()
        }
        self.assertEqual(actual, expected)
        self.assertEqual(len(actual), len(expected))
        self.assertFalse((runtime_dir / LEGACY_RUNTIME_TARGET_NAME).exists())


if __name__ == "__main__":
    unittest.main()
