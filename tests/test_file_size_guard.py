"""Exercise the guard with real staged Git blobs, without touching the caller's index."""
import json
import os
import shutil
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
GUARD = ROOT / 'scripts/file_size_guard.py'


class FileSizeGuardTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.repo = Path(self.tmp.name)
        self.env = {k: v for k, v in os.environ.items() if not k.startswith('GIT_')}
        self.env.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM='1')
        self.git('init', '-q')
        self.git('config', 'user.name', 'Test')
        self.git('config', 'user.email', 'test@example.invalid')
        self.git('config', 'commit.gpgsign', 'false')

    def git(self, *args):
        return subprocess.run(['git', *args], cwd=self.repo, env=self.env,
                              capture_output=True, check=True)

    def stage(self, path, content):
        dest = self.repo / path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(content)
        self.git('add', '--', path)

    def commit(self):
        self.git('commit', '-qm', 'fixture')

    def guard(self):
        return subprocess.run([sys.executable, str(GUARD), '--plain'],
                              cwd=self.repo, env=self.env, capture_output=True, text=True)

    def test_new_big_file_blocked(self):
        self.stage('large.py', b'x' * 20001)
        result = self.guard()
        self.assertEqual(result.returncode, 1, result.stderr)
        self.assertIn('large.py', result.stderr)
        self.assertIn('5,000.25 tokens', result.stderr)
        self.assertIn('+5,000.25', result.stderr)
        self.assertIn('2 files', result.stderr)
        for instruction in ('responsibility', 'verbatim', 're-export', 'tests'):
            self.assertIn(instruction, result.stderr)

    def test_existing_big_shrinking_allowed(self):
        self.stage('large.py', b'x' * 24000)
        self.commit()
        self.stage('large.py', b'x' * 22000)
        self.assertEqual(self.guard().returncode, 0)

    def test_existing_big_growing_blocked(self):
        self.stage('large.py', b'x' * 24000)
        self.commit()
        self.stage('large.py', b'x' * 24004)
        result = self.guard()
        self.assertEqual(result.returncode, 1)
        self.assertIn('+1 tokens', result.stderr)

    def test_boundary_and_crossing_limit(self):
        self.stage('code.py', b'x' * 20000)
        self.assertEqual(self.guard().returncode, 0)
        self.commit()
        self.stage('code.py', b'x' * 20001)
        self.assertEqual(self.guard().returncode, 1)

    def test_index_content_only(self):
        self.stage('code.py', b'x' * 20001)
        (self.repo / 'code.py').write_bytes(b'small')
        self.assertEqual(self.guard().returncode, 1)
        self.stage('code.py', b'small')
        (self.repo / 'code.py').write_bytes(b'x' * 24000)
        self.assertEqual(self.guard().returncode, 0)

    def test_skipped_paths_ignored(self):
        for path in ('package-lock.json', 'nested/yarn.lock', 'web/app.min.js',
                     'nested/data/sample.txt', 'vendor/lib/code.py'):
            self.stage(path, b'x' * 24000)
        self.stage('binary.dat', b'\0' + b'x' * 24000)
        self.stage('generated.py', b'# Code generated by fixture. DO NOT EDIT.\n' + b'x' * 24000)
        self.stage('upstream/SOURCE.md', b'https://example.invalid/upstream\n')
        self.stage('upstream/code.py', b'x' * 24000)
        self.stage('dot_agents/skills/licensed/LICENSE', b'Upstream license')
        self.stage('dot_agents/skills/licensed/code.py', b'x' * 24000)
        self.stage('.gitattributes', b'lfs-code.py filter=lfs\n')
        self.git('-c', 'filter.lfs.process=', '-c', 'filter.lfs.required=false',
                 'add', '.gitattributes')
        # Plumbing avoids requiring git-lfs in the fixture.
        blob = subprocess.run(['git', 'hash-object', '-w', '--stdin'], input=b'x' * 24000,
                              cwd=self.repo, env=self.env, capture_output=True, check=True).stdout.strip()
        self.git('update-index', '--add', '--cacheinfo', '100644', blob.decode(), 'lfs-code.py')
        self.assertEqual(self.guard().returncode, 0, self.guard().stderr)

    def test_skip_markers_and_attributes_use_index(self):
        self.stage('nested/SOURCE.md', b'upstream')
        self.stage('nested/code.py', b'x' * 24000)
        (self.repo / 'nested/SOURCE.md').unlink()
        self.assertEqual(self.guard().returncode, 0)
        self.git('rm', '-f', 'nested/SOURCE.md')
        (self.repo / 'nested/SOURCE.md').write_bytes(b'unstaged provenance')
        self.assertEqual(self.guard().returncode, 1)

    def test_report_uses_head_attributes(self):
        self.stage('code.py', b'x' * 24000)
        self.commit()
        self.stage('.gitattributes', b'code.py -diff\n')
        result = subprocess.run([sys.executable, str(GUARD), '--report', '--plain'],
                                cwd=self.repo, env=self.env, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('1 eligible tracked files', result.stdout)
        self.assertIn('code.py', result.stdout)

    def test_identical_oversized_file_allowed(self):
        self.stage('code.py', b'x' * 24000)
        self.commit()
        self.git('update-index', '--chmod=+x', 'code.py')
        self.assertEqual(self.guard().returncode, 0)

    def install(self):
        for name in ('hooks/pre-commit', 'scripts/install_commit_hook.py',
                     'scripts/file_size_guard.py', 'config/file-size-guard.json'):
            source = ROOT / name
            self.assertTrue(source.exists(), f'Missing hook integration: {name}')
            dest = self.repo / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, dest)
        return subprocess.run([sys.executable, 'scripts/install_commit_hook.py', '--plain'],
                              cwd=self.repo, env=self.env, capture_output=True, text=True)

    def test_installer_wires_real_commit_and_preserves_lfs_hooks(self):
        lfs_hook = self.repo / '.git/hooks/pre-push'
        lfs_hook.write_text('# existing git-lfs hook\n')
        result = self.install()
        self.assertEqual(result.returncode, 0, result.stderr)
        hook = self.repo / '.git/hooks/pre-commit'
        self.assertTrue(hook.is_symlink())
        self.assertEqual(hook.resolve(), self.repo / 'hooks/pre-commit')
        self.assertEqual(self.install().returncode, 0)
        self.assertEqual(lfs_hook.read_text(), '# existing git-lfs hook\n')
        config = subprocess.run(['git', 'config', '--get', 'core.hooksPath'],
                                cwd=self.repo, env=self.env, capture_output=True)
        self.assertEqual(config.returncode, 1)
        self.stage('code.py', b'x' * 20001)
        result = subprocess.run(['git', '-c', 'commit.gpgsign=false', 'commit', '-qm', 'blocked'],
                                cwd=self.repo, env=self.env, capture_output=True, text=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn('Staged file-size guard', result.stderr)
        self.stage('code.py', b'x' * 20000)
        self.commit()

    def test_installer_preserves_existing_hook_and_its_veto(self):
        hook = self.repo / '.git/hooks/pre-commit'
        original = '#!/bin/sh\nprintf ran >> hook-ran\nexit 17\n'
        hook.write_text(original)
        hook.chmod(0o755)
        result = self.install()
        self.assertEqual(result.returncode, 0, result.stderr)
        backup = hook.with_name('pre-commit.file-size-previous')
        self.assertEqual(backup.read_text(), original)
        self.assertEqual(self.install().returncode, 0)
        self.stage('safe.txt', b'public example\n')
        result = subprocess.run(['git', 'commit', '-qm', 'blocked'], cwd=self.repo,
                                env=self.env, capture_output=True)
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual((self.repo / 'hook-ran').read_text(), 'ran')

    def test_size_check_runs_after_preserved_hook_index_changes(self):
        hook = self.repo / '.git/hooks/pre-commit'
        hook.write_text("#!/bin/sh\npython3 -c \"from pathlib import Path; Path('large.py').write_bytes(b'x' * 20001)\"\ngit add large.py\n")
        hook.chmod(0o755)
        self.assertEqual(self.install().returncode, 0)
        self.stage('safe.txt', b'public example\n')
        result = subprocess.run(['git', 'commit', '-qm', 'blocked'], cwd=self.repo,
                                env=self.env, capture_output=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn(b'Staged file-size guard', result.stderr)

    def test_installer_keeps_privacy_gate_enforced(self):
        gate = ROOT / 'scripts/executable_privacy-gate'
        result = subprocess.run([sys.executable, str(gate), '--repo', str(self.repo), 'install'],
                                cwd=self.repo, env=self.env, capture_output=True)
        self.assertEqual(result.returncode, 0, 'privacy fixture installation failed')
        hook = self.repo / '.git/hooks/pre-commit'
        original = hook.read_bytes()
        self.assertEqual(self.install().returncode, 0)
        self.assertEqual(hook.with_name('pre-commit.file-size-previous').read_bytes(), original)
        self.stage('safe.txt', b'public example\n')
        self.commit()
        self.stage('unsafe.txt', ('ghp_' + 'a' * 36).encode())
        result = subprocess.run(['git', 'commit', '-qm', 'blocked'], cwd=self.repo,
                                env=self.env, capture_output=True)
        self.assertEqual(result.returncode, 1, 'preserved privacy gate must reject secret fixture')
        self.assertIn(b'Privacy gate BLOCKED', result.stderr)

    def test_installer_refuses_dangling_symlink_and_conflicting_backup(self):
        hook = self.repo / '.git/hooks/pre-commit'
        hook.symlink_to('missing-hook')
        self.assertEqual(self.install().returncode, 1)
        self.assertEqual(os.readlink(hook), 'missing-hook')
        hook.unlink()
        backup = hook.with_name('pre-commit.file-size-previous')
        backup.write_text('preserve me')
        self.assertEqual(self.install().returncode, 1)
        self.assertEqual(backup.read_text(), 'preserve me')
        self.assertFalse(hook.exists())

    def test_installer_uses_common_hooks_in_linked_worktree(self):
        self.stage('small.py', b'pass\n')
        self.commit()
        common = self.repo / '.git'
        linked = self.repo / 'linked checkout'
        self.git('worktree', 'add', '-qb', 'linked-test', str(linked))
        self.repo = linked
        result = self.install()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual((common / 'hooks/pre-commit').resolve(), linked / 'hooks/pre-commit')
        self.stage('large.py', b'x' * 20001)
        result = subprocess.run(['git', '-c', 'commit.gpgsign=false', 'commit', '-qm', 'blocked'],
                                cwd=linked, env=self.env, capture_output=True, text=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn('Staged file-size guard', result.stderr)

    def test_installer_refuses_configured_hooks_path(self):
        self.git('config', 'core.hooksPath', '/dev/null')
        result = self.install()
        self.assertEqual(result.returncode, 1)
        self.assertIn('core.hooksPath', result.stderr)
        self.assertFalse((self.repo / '.git/hooks/pre-commit').exists())

    def test_grandfathered_ceiling_is_exact_and_only_for_existing_paths(self):
        self.stage('legacy.md', b'x' * 24000)
        self.commit()
        self.assertEqual(self.install().returncode, 0)
        config = self.repo / 'config/file-size-guard.json'
        settings = json.loads(config.read_text())
        settings['grandfathered_max_bytes'] = {'legacy.md': 24004, 'new.md': 25000}
        config.write_text(json.dumps(settings))
        command = [sys.executable, 'scripts/file_size_guard.py', '--plain']
        self.stage('legacy.md', b'x' * 24004)
        result = subprocess.run(command, cwd=self.repo, env=self.env, capture_output=True)
        self.assertEqual(result.returncode, 0)
        self.stage('legacy.md', b'x' * 24005)
        result = subprocess.run(command, cwd=self.repo, env=self.env, capture_output=True)
        self.assertEqual(result.returncode, 1)
        self.stage('legacy.md', b'x' * 24000)
        self.stage('new.md', b'x' * 24001)
        result = subprocess.run(command, cwd=self.repo, env=self.env, capture_output=True)
        self.assertEqual(result.returncode, 1, 'new paths cannot use a grandfathered ceiling')

    def test_invalid_grandfathered_ceiling_fails_closed(self):
        self.assertEqual(self.install().returncode, 0)
        config = self.repo / 'config/file-size-guard.json'
        settings = json.loads(config.read_text())
        for invalid in (True, 19999, '25000'):
            settings['grandfathered_max_bytes'] = {'legacy.md': invalid}
            config.write_text(json.dumps(settings))
            result = subprocess.run([sys.executable, 'scripts/file_size_guard.py', '--plain'],
                                    cwd=self.repo, env=self.env, capture_output=True)
            self.assertEqual(result.returncode, 2, 'invalid configuration must fail closed')

    def test_malformed_config_fails_with_actionable_error(self):
        self.assertEqual(self.install().returncode, 0)
        self.stage('large.py', b'x' * 20001)
        config = self.repo / 'config/file-size-guard.json'
        valid = json.loads(config.read_text())
        for invalid in ([], {**valid, 'skip_globs': [1]}):
            config.write_text(json.dumps(invalid))
            result = subprocess.run([sys.executable, 'scripts/file_size_guard.py', '--plain'],
                                    cwd=self.repo, env=self.env, capture_output=True)
            self.assertEqual(result.returncode, 2)
            self.assertIn(b'Check Git/index state and config/file-size-guard.json', result.stderr)
            self.assertNotIn(b'Traceback', result.stderr)

    def test_authored_license_and_generated_string_are_not_exemptions(self):
        self.stage('app/LICENSE', b'Own module license')
        self.stage('app/code.py', b'x' * 24000)
        self.stage('generator.py', b"HEADER = '# Code generated by tool. DO NOT EDIT.'\n" + b'x' * 24000)
        result = self.guard()
        self.assertEqual(result.returncode, 1)
        self.assertIn('app/code.py', result.stderr)
        self.assertIn('generator.py', result.stderr)

    def test_binary_extension_and_attribute_are_skipped(self):
        self.stage('attachment.pdf', b'%PDF-1.7\n' + b'x' * 24000)
        self.stage('.gitattributes', b'opaque.payload -diff\n')
        self.stage('opaque.payload', b'x' * 24000)
        self.assertEqual(self.guard().returncode, 0)

    def test_root_license_does_not_exempt_repo(self):
        self.stage('LICENSE', b'Repo license')
        self.stage('authored.py', b'x' * 24000)
        self.assertEqual(self.guard().returncode, 1)

    def test_delete_and_rename_oversized_file(self):
        self.stage('old.py', b'x' * 24000)
        self.commit()
        self.git('mv', 'old.py', 'new name.py')
        self.assertEqual(self.guard().returncode, 0)
        self.git('rm', '-f', 'new name.py')
        self.assertEqual(self.guard().returncode, 0)

    def test_multiple_files_and_unusual_names(self):
        self.stage('space name.py', b'x' * 24000)
        self.stage('line\nbreak.py', b'x' * 40001)
        result = self.guard()
        self.assertEqual(result.returncode, 1)
        self.assertIn('space name.py', result.stderr)
        self.assertIn('line\\nbreak.py', result.stderr)
        self.assertIn('3 files', result.stderr)


if __name__ == '__main__':
    unittest.main()
